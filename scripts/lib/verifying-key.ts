/**
 * Node-only helpers for the Semaphore v4 verifying key.
 *
 * Reads the verification key shipped inside @semaphore-protocol/proof (the same
 * file `verifyProof` uses) and converts the entry for MERKLE_TREE_DEPTH into the
 * byte layout groth16-solana expects:
 *   G1: x(32, BE) | y(32, BE)
 *   G2: x.c1 | x.c0 | y.c1 | y.c0   (each 32 bytes BE, imaginary part first)
 */
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import path from "node:path";
import { bigintToBytes32, bytesToHex, concatBytes, parseBigint } from "../../src/lib/zk/field";
import { MERKLE_TREE_DEPTH, SEMAPHORE_PACKAGE_VERSION } from "../../src/lib/zk/constants";

export interface SnarkjsVerificationKey {
  protocol: string;
  curve: string;
  nPublic: number;
  vk_alpha_1: string[];
  vk_beta_2: string[][];
  vk_gamma_2: string[][];
  vk_delta_2: string[][];
  vk_alphabeta_12?: unknown;
  IC: string[][];
}

interface SemaphoreVerificationKeys {
  protocol: string;
  curve: string;
  nPublic: number;
  vk_alpha_1: string[];
  vk_beta_2: string[][];
  vk_gamma_2: string[][];
  vk_delta_2: string[][][];
  IC: string[][][];
}

export function semaphoreVerificationKeysPath(): string {
  // The package's `exports` map hides package.json, so locate the folder via node_modules.
  const candidates = [
    path.resolve(process.cwd(), "node_modules/@semaphore-protocol/proof/src/verification-keys.json"),
  ];
  for (const c of candidates) {
    try {
      readFileSync(c);
      return c;
    } catch {
      /* try next */
    }
  }
  throw new Error("verification-keys.json not found; run npm install first");
}

export function loadSemaphoreVerificationKeys(): { keys: SemaphoreVerificationKeys; sha256: string } {
  const file = semaphoreVerificationKeysPath();
  const raw = readFileSync(file);
  const sha256 = createHash("sha256").update(raw).digest("hex");
  return { keys: JSON.parse(raw.toString("utf8")) as SemaphoreVerificationKeys, sha256 };
}

/** snarkjs-shaped verification key for one tree depth (what groth16.verify consumes). */
export function verificationKeyForDepth(depth = MERKLE_TREE_DEPTH): SnarkjsVerificationKey {
  const { keys } = loadSemaphoreVerificationKeys();
  if (depth < 1 || depth > keys.vk_delta_2.length) throw new RangeError(`no verifying key for depth ${depth}`);
  return {
    protocol: keys.protocol,
    curve: keys.curve,
    nPublic: keys.nPublic,
    vk_alpha_1: keys.vk_alpha_1,
    vk_beta_2: keys.vk_beta_2,
    vk_gamma_2: keys.vk_gamma_2,
    vk_delta_2: keys.vk_delta_2[depth - 1],
    IC: keys.IC[depth - 1],
  };
}

export function g1ToSolanaBytes(point: string[]): Uint8Array {
  const [x, y, z] = point;
  if (z !== undefined && parseBigint(z) !== 1n) throw new RangeError("expected affine G1 point (z == 1)");
  return concatBytes(bigintToBytes32(parseBigint(x)), bigintToBytes32(parseBigint(y)));
}

export function g2ToSolanaBytes(point: string[][]): Uint8Array {
  const [x, y, z] = point;
  if (z !== undefined && (parseBigint(z[0]) !== 1n || parseBigint(z[1]) !== 0n)) {
    throw new RangeError("expected affine G2 point (z == (1, 0))");
  }
  return concatBytes(
    bigintToBytes32(parseBigint(x[1])),
    bigintToBytes32(parseBigint(x[0])),
    bigintToBytes32(parseBigint(y[1])),
    bigintToBytes32(parseBigint(y[0])),
  );
}

export interface SolanaVerifyingKey {
  nrPublicInputs: number;
  alphaG1: Uint8Array;
  betaG2: Uint8Array;
  gammaG2: Uint8Array;
  deltaG2: Uint8Array;
  ic: Uint8Array[];
}

export function toSolanaVerifyingKey(vk: SnarkjsVerificationKey): SolanaVerifyingKey {
  return {
    nrPublicInputs: vk.nPublic,
    alphaG1: g1ToSolanaBytes(vk.vk_alpha_1),
    betaG2: g2ToSolanaBytes(vk.vk_beta_2),
    gammaG2: g2ToSolanaBytes(vk.vk_gamma_2),
    deltaG2: g2ToSolanaBytes(vk.vk_delta_2),
    ic: vk.IC.map(g1ToSolanaBytes),
  };
}

function rustArray(bytes: Uint8Array, indent: string): string {
  const lines: string[] = [];
  for (let i = 0; i < bytes.length; i += 16) {
    lines.push(
      indent +
        Array.from(bytes.slice(i, i + 16), (b) => `0x${b.toString(16).padStart(2, "0")}`).join(", ") +
        ",",
    );
  }
  return lines.join("\n");
}

/** Render the verifying key as a Rust module consumed by the Solana program. */
export function renderRustVerifyingKey(depth = MERKLE_TREE_DEPTH): string {
  const { sha256 } = loadSemaphoreVerificationKeys();
  const vk = verificationKeyForDepth(depth);
  const sol = toSolanaVerifyingKey(vk);
  if (sol.ic.length !== sol.nrPublicInputs + 1) throw new Error("IC length must be nPublic + 1");

  const icBlocks = sol.ic
    .map((p, i) => `    // IC[${i}]\n    [\n${rustArray(p, "        ")}\n    ],`)
    .join("\n");

  return `//! AUTO-GENERATED by scripts/gen-verifying-key.ts. Do not edit by hand.
//!
//! Groth16 verifying key for the Semaphore v4 circuit at Merkle tree depth ${depth}.
//! Source: @semaphore-protocol/proof@${SEMAPHORE_PACKAGE_VERSION} src/verification-keys.json
//!   (sha256 ${sha256}), entry vk_delta_2[${depth - 1}] / IC[${depth - 1}].
//! Protocol: ${vk.protocol}, curve: ${vk.curve}, public inputs: ${vk.nPublic}
//!   [merkleTreeRoot, nullifier, hash(message), hash(scope)].
//! Byte layout: big-endian 32-byte limbs; G2 coordinates ordered (c1, c0),
//! the convention shared by the EVM precompiles and Solana's alt_bn128 syscalls.
//! See docs/ARTIFACTS.md for the trusted setup provenance.

use groth16_solana::groth16::Groth16Verifyingkey;

pub const MERKLE_TREE_DEPTH: u8 = ${depth};
pub const NR_PUBLIC_INPUTS: usize = ${vk.nPublic};

pub const VERIFYING_KEY: Groth16Verifyingkey = Groth16Verifyingkey {
    nr_pubinputs: ${vk.nPublic},

    vk_alpha_g1: [
${rustArray(sol.alphaG1, "        ")}
    ],

    vk_beta_g2: [
${rustArray(sol.betaG2, "        ")}
    ],

    vk_gamme_g2: [
${rustArray(sol.gammaG2, "        ")}
    ],

    vk_delta_g2: [
${rustArray(sol.deltaG2, "        ")}
    ],

    vk_ic: &[
${icBlocks}
    ],
};
`;
}

export function solanaVerifyingKeyHex(depth = MERKLE_TREE_DEPTH): Record<string, string | string[]> {
  const sol = toSolanaVerifyingKey(verificationKeyForDepth(depth));
  return {
    alphaG1: bytesToHex(sol.alphaG1),
    betaG2: bytesToHex(sol.betaG2),
    gammaG2: bytesToHex(sol.gammaG2),
    deltaG2: bytesToHex(sol.deltaG2),
    ic: sol.ic.map(bytesToHex),
  };
}
